// Helper function to calculate total gear bonuses for a given stat
export function calculateGearBonus(gearOwned: string[], stat: string): number {
  return GEAR_DB
    .filter(item => gearOwned.includes(item.id))
    .reduce((total, item) => {
      const bonus = item.statBonus[stat as keyof typeof item.statBonus];
      return total + (typeof bonus === 'number' ? bonus : 0);
    }, 0);
}

// Get all unique stats that gear can affect
export function getAllGearStats(): string[] {
  const stats = new Set<string>();
  GEAR_DB.forEach(item => {
    Object.keys(item.statBonus).forEach(stat => stats.add(stat));
  });
  return Array.from(stats);
}

// Get gear items filtered by category
export function getGearByCategory(category: string): GearItem[] {
  return GEAR_DB.filter(item => item.category === category);
}

// Get gear items sorted by unlock prestige
export function getGearSortedByPrestige(): GearItem[] {
  return [...GEAR_DB].sort((a, b) => a.unlockedAtPrestige - b.unlockedAtPrestige);
}

// Get the total number of gear items
export function getGearCount(): number {
  return GEAR_DB.length;
}

// Get the count of owned vs unlockable gear
export function getGearStats(gearOwned: string[]): { owned: number; unlockable: number; total: number } {
  return {
    owned: gearOwned.length,
    unlockable: GEAR_DB.filter(item => item.unlockedAtPrestige > 0 && !gearOwned.includes(item.id)).length,
    total: GEAR_DB.length
  };
}

// Helper to get gear that affects specific stats
export function getGearByStat(stat: string): GearItem[] {
  return GEAR_DB.filter(item => item.statBonus && stat in item.statBonus);
}

// Get gear tier colors for UI
export function getTierColor(tier: string | undefined): string {
  switch (tier) {
    case "starter": return "bg-slate-600";
    case "basic": return "bg-blue-700";
    case "utility": return "bg-cyan-700";
    case "advanced": return "bg-purple-700";
    case "custom": return "bg-amber-700";
    case "legendary": return "bg-rose-800";
    default: return "bg-slate-700";
  }
}

// Get tier display name
export function getTierName(tier: string | undefined): string {
  switch (tier) {
    case "starter": return "Starter";
    case "basic": return "Basic";
    case "utility": return "Utility";
    case "advanced": return "Advanced";
    case "custom": return "Custom Stage";
    case "legendary": return "Legendary";
    default: return "Standard";
  }
}
